export const t = (lang, key) =>
  TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en[key] ?? key;

export const timeAgo = (dateStr, lang = 'en') => {
  const tx = TRANSLATIONS[lang] ?? TRANSLATIONS.en;
  const diff = Math.floor((Date.now() - new Date(dateStr)) / 1000);
  if (diff < 60)   return tx.just_now;
  if (diff < 3600) return `${Math.floor(diff / 60)} ${tx.min_ago}`;
  if (diff < 86400)return `${Math.floor(diff / 3600)} ${tx.hr_ago}`;
  return `${Math.floor(diff / 86400)} ${tx.day_ago}`;
};
